const https = require('https');
const { dlog } = require('./utils');

function githubApiGet(pathname, bearerToken) {
	dlog('GitHub GET', pathname, bearerToken ? '(with token)' : '(no token)');
	const options = {
		hostname: 'api.github.com',
		path: pathname,
		method: 'GET',
		headers: {
			'User-Agent': 'ScanBase',
			'Accept': 'application/vnd.github+json'
		}
	};
	const token = bearerToken || process.env.GITHUB_TOKEN;
	if (token) options.headers.Authorization = `Bearer ${token}`;
	return new Promise((resolve, reject) => {
		const TIMEOUT = 30000; // 30 seconds
		const req = https.get(options, (resp) => {
			let data = '';
			resp.on('data', (chunk) => { data += chunk; });
			resp.on('end', () => {
				clearTimeout(timeout);
				const status = resp.statusCode || 0;
				const headers = resp.headers || {};
				dlog('GitHub RESP', pathname, 'status=', status);
				if (status >= 200 && status < 300) {
					let parsed = null;
					try {
						parsed = JSON.parse(data);
					} catch (e) {
						// not JSON; keep as text
					}
					resolve({ statusCode: status, headers, data: parsed !== null ? parsed : data });
				} else {
					reject(new Error(`GitHub API error ${status}: ${data}`));
				}
			});
		});
		
		const timeout = setTimeout(() => {
			req.destroy();
			reject(new Error('Request timeout'));
		}, TIMEOUT);
		
		req.on('error', (err) => {
			clearTimeout(timeout);
			reject(err);
		});
	});
}

async function fetchRepoFile(ownerRepo, filePath, ref, bearerToken) {
	const encPath = encodeURIComponent(filePath).replace(/%2F/g, '/');
	const ghPath = `/repos/${ownerRepo}/contents/${encPath}${ref ? `?ref=${encodeURIComponent(ref)}` : ''}`;
	const response = await githubApiGet(ghPath, bearerToken);
	const contentResp = response && response.data;
	if (!contentResp || !contentResp.content || contentResp.encoding !== 'base64') {
		throw new Error('Unsupported or missing file content');
	}
	const buff = Buffer.from(contentResp.content, 'base64');
	return buff.toString('utf-8');
}

async function fetchGithubRepoSbom(ownerRepo, ref, bearerToken) {
	const ghPath = `/repos/${ownerRepo}/dependency-graph/sbom${ref ? `?ref=${encodeURIComponent(ref)}` : ''}`;
	dlog('Fetch SBOM for repo', ownerRepo, 'ref=', ref || '(default)');
	const response = await githubApiGet(ghPath, bearerToken);
	if (response.statusCode === 202) {
		throw new Error('SBOM is being generated by GitHub. Please retry in a moment.');
	}
	const body = response.data;
	if (body && typeof body === 'object') {
		// standard shape: { sbom: { ... CycloneDX ... } }
		if (body.sbom) {
			const sbom = body.sbom;
			if (typeof sbom === 'string') {
				try { return JSON.stringify(JSON.parse(sbom)); } catch (e) { throw new Error('Invalid SBOM JSON from GitHub'); }
			}
			return JSON.stringify(sbom);
		}
		// Sometimes GitHub returns the SBOM object directly (rare). Handle it.
		return JSON.stringify(body);
	}
	// Non-JSON body
	throw new Error('Unexpected response from GitHub SBOM API');
}

module.exports = {
	githubApiGet,
	fetchRepoFile,
	fetchGithubRepoSbom
};

